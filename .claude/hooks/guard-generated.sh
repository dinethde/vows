#!/usr/bin/env bash
# PreToolUse on Write|Edit|MultiEdit. Exit 2 blocks the call.
set -euo pipefail
INPUT=$(cat)
FILE=$(printf '%s' "$INPUT" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
[ -z "$FILE" ] && exit 0

case "$FILE" in
  *packages/tokens/css/*.css|*packages/tokens/src/index.ts)
    echo "Generated by pnpm tokens:build from Figma. Change the variable in Figma, export, rebuild." >&2
    exit 2 ;;
  *pnpm-lock.yaml)
    echo "Lockfiles are written by pnpm, not by hand." >&2
    exit 2 ;;
  *.env|*.env.local|*.env.production)
    echo "Real secrets never enter the repo. Use .env.example, and the vault for values." >&2
    exit 2 ;;
esac
exit 0
